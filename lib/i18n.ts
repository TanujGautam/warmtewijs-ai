export const DICTS: Record<Lang, Dict> = { en, nl };
export type { Dict };

export function isLang(v: unknown): v is Lang {
  return v === "en" || v === "nl";
}

/** Pick a language from a cookie value or an Accept-Language header. Dutch is the default market. */
export function resolveLang(cookie?: string | null, acceptLanguage?: string | null): Lang {
  if (isLang(cookie)) return cookie;
  if (acceptLanguage && /^\s*en\b/i.test(acceptLanguage) && !/\bnl\b/i.test(acceptLanguage)) return "en";
  return "nl";
}
